function env(key, fallback = undefined) {
  const value = process.env[key];
  return value === undefined || value === "" ? fallback : value;
}

function envList(key, fallback = []) {
  const value = env(key);
  if (!value) return fallback;
  return String(value)
    .split(",")
    .map((v) => v.replace(/[^0-9]/g, ""))
    .filter(Boolean);
}

