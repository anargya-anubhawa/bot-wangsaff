/* ─────────────────────────── helper functions ─────────────────────────── */

function cleanNumber(value) {
  if (value === undefined || value === null) return "";
  return String(value).split(":")[0].split("@")[0].replace(/[^0-9]/g, "");
}

function numberMatches(a, b) {
  const x = cleanNumber(a);
  const y = cleanNumber(b);
  if (!x || !y) return false;
  return x === y || x.endsWith(y) || y.endsWith(x);
}

function isOwner(number) {
  const target = cleanNumber(number);
  if (!target) return false;

  if (config.bot?.number && numberMatches(target, config.bot.number)) return true;

  if (Array.isArray(config.owner?.number)) {
    if (config.owner.number.some((own) => numberMatches(target, own))) return true;
  }

  try {
    const db = getDatabase();
    if (!db) return false;

    if (Array.isArray(db.data?.owner) && db.data.owner.some((o) => numberMatches(target, o))) {
      return true;
    }
    const extra = db.setting("ownerNumbers");
    if (Array.isArray(extra) && extra.some((o) => numberMatches(target, o))) {
      return true;
    }
  } catch {
    /* database not ready yet */
  }

  return false;
}

function isBanned(number) {
  const target = cleanNumber(number);
  if (!target) return false;
  if (isOwner(target)) return false;

  let list = [];
  try {
    const db = getDatabase();
    list = db.setting("bannedUsers") || [];
  } catch {
    /* ignore */
  }
  return list.some((b) => numberMatches(target, b));
}

/**
 * Premium / partner checks used by the GX game subsystem. Premium status lives
 * in the user record and in the `premiumUsers` / `partnerUsers` settings lists.
 */
function isPremium(number) {
  const target = cleanNumber(number);
  if (!target) return false;
  if (isOwner(target)) return true;

  try {
    const db = getDatabase();
    const user = db.getUser(target);
    if (user?.isPremium) return true;
    const list = db.setting("premiumUsers") || [];
    if (list.some((p) => numberMatches(target, p))) return true;
  } catch {
    /* ignore */
  }
  return false;
}

function isPartner(number) {
  const target = cleanNumber(number);
  if (!target) return false;
  if (isOwner(target)) return true;

  try {
    const db = getDatabase();
    const list = db.setting("partnerUsers") || [];
    if (list.some((p) => numberMatches(target, p))) return true;
  } catch {
    /* ignore */
  }
  return false;
}

function setBotNumber(number) {
  if (number) config.bot.number = cleanNumber(number);
}

function isSelf(number) {
  return numberMatches(number, config.bot.number);
}

